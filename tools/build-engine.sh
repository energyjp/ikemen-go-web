#!/usr/bin/env bash
# Build the wasm engine AND stamp what went into it.
#
# WHY THIS EXISTS. On 2026-08-28 a desync that had reproduced three times in a
# row stopped after a rebuild, and it was impossible to say whether a code change
# had fixed it or whether the previously-shipped binary had simply never
# contained the full source tree. The old wasm was overwritten, nothing recorded
# what produced it, and two source files carried mtimes inside the same MINUTE
# the binary was written - so "same source, rebuilt" could not be confirmed or
# denied. That question should never be unanswerable again.
#
# The stamp records the engine hash, the exact build line, and a per-file hash of
# every Go source that went in. Given any shipped engine and any tree, you can
# now say definitively whether they match.
#
# Usage:  bash tools/build-engine.sh
set -euo pipefail

cd "$(dirname "$0")/.."

# -buildvcs=false is REQUIRED for this stamp to mean anything. Go embeds the git
# revision and a dirty-tree flag into the binary by default, so the SAME source
# produced a different engine before and after being committed - which makes
# "was this engine built from this tree?" unanswerable, the exact question this
# script exists to answer. The commit is recorded IN the stamp below instead,
# where it is data rather than a hidden build input.
OUT=bin/ikemen-v2.wasm
STAMP=bin/ikemen-v2.wasm.build.txt
BUILD_CMD='GOEXPERIMENT=arenas GOOS=js GOARCH=wasm CGO_ENABLED=0 go build -trimpath -buildvcs=false -o '"$OUT"' ./src'

# Hash the inputs BEFORE building, so the stamp describes what was compiled even
# if someone edits a file while the build runs.
srclist=$(mktemp)
find src third_party -name '*.go' | LC_ALL=C sort > "$srclist"
tree_hash=$(xargs sha256sum < "$srclist" | sha256sum | cut -d' ' -f1)

echo "building $OUT ..."
env GOEXPERIMENT=arenas GOOS=js GOARCH=wasm CGO_ENABLED=0 \
    go build -trimpath -buildvcs=false -o "$OUT" ./src

engine_sha=$(sha256sum "$OUT" | cut -d' ' -f1)

{
    echo "# Ikemen GO wasm engine build stamp"
    echo "# Generated by tools/build-engine.sh - do not hand-edit."
    echo
    echo "engine_sha256 = $engine_sha"
    echo "engine_bytes  = $(wc -c < "$OUT" | tr -d ' ')"
    echo "source_tree_sha256 = $tree_hash"
    echo "build_command = $BUILD_CMD"
    echo "go_version = $(go version)"
    if git rev-parse --git-dir >/dev/null 2>&1; then
        echo "git_commit = $(git rev-parse HEAD 2>/dev/null || echo unknown)"
        dirty=$(git status --porcelain 2>/dev/null | wc -l | tr -d ' ')
        echo "git_dirty_files = $dirty"
        if [ "$dirty" != "0" ]; then
            echo "# WARNING: built from a DIRTY tree. The commit above does NOT"
            echo "# describe this binary; source_file_sha256 below does."
        fi
    fi
    echo
    echo "# Every Go file that went into this binary."
    echo "[source_file_sha256]"
    xargs sha256sum < "$srclist"
} > "$STAMP"

rm -f "$srclist"

echo
echo "engine   $engine_sha"
echo "src tree $tree_hash"
echo "stamp    $STAMP"
echo
echo "Ship the stamp NEXT TO the engine. To check a deployed engine later:"
echo "  sha256sum <deployed>/ikemen.wasm   # compare with engine_sha256"
